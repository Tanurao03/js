console.log(null > 0);  // these sign change null to number
console.log(null >= 0);
console.log(null == 0);   // equality does not 

console.log(undefined > 0);
console.log(undefined >= 0);
console.log(undefined == 0);

console.log("2" > 0);

console.log("2" == 2);    // convert to number
console.log("2" === 2);   // not converted
